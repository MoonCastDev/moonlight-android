#!/bin/sh
# Regenerates ../shaders_spv.h from pyrowave.vert and pyrowave.frag. Run after editing a shader.
# Uses the glslc that ships with the NDK (ndk/<version>/shader-tools/<host>/glslc).
set -e

cd "$(dirname "$0")"

GLSLC="${GLSLC:-glslc}"
OUT=../shaders_spv.h

{
    echo "// Generated by shaders/compile_shaders.sh from pyrowave.vert and pyrowave.frag. Do not edit."
    echo "#pragma once"
    echo "#include <cstdint>"
    echo
    echo "static const uint32_t kPyrowaveVertSpv[] ="
    "$GLSLC" -O --target-env=vulkan1.1 -mfmt=c -o - pyrowave.vert
    echo ";"
    echo
    echo "static const uint32_t kPyrowaveFragSpv[] ="
    "$GLSLC" -O --target-env=vulkan1.1 -mfmt=c -o - pyrowave.frag
    echo ";"
} > "$OUT"

echo "Wrote $OUT"
